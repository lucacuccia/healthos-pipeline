def run_setup():
    """Interactive setup wizard that walks through configuration."""
    print()
    print("Health OS Setup")
    print("=" * 40)
    print()

    # Phase 0: Detect existing config
    existing = _read_existing_env()
    if existing:
        print(f"  Found existing .env with {len(existing)} variables.")
        if not _prompt_yn("Update it?", default=True):
            print("  Setup cancelled.")
            return
        print()

    config = dict(existing)  # start from existing values

    # Phase 1: Data sources
    print("Data Sources")
    print("-" * 40)
    print("  Choose which provider to use for each data type.")
    print()

    config["SLEEP_SOURCE"] = _prompt_choice(
        "Sleep source",
        ["oura", "apple_health", "manual"],
        default=config.get("SLEEP_SOURCE", "oura"),
    )
    config["WORKOUT_SOURCE"] = _prompt_choice(
        "Workout source",
        ["firestore", "sheets", "apple_health", "manual"],
        default=config.get("WORKOUT_SOURCE", "firestore"),
    )
    config["WEIGHT_SOURCE"] = _prompt_choice(
        "Weight source",
        ["firestore", "sheets", "apple_health", "manual"],
        default=config.get("WEIGHT_SOURCE", "firestore"),
    )
    print()

    # Phase 2: Credentials (conditional)
    print("Credentials")
    print("-" * 40)

    needs_oura = config["SLEEP_SOURCE"] == "oura"
    needs_apple = "apple_health" in (config["SLEEP_SOURCE"], config["WORKOUT_SOURCE"], config["WEIGHT_SOURCE"])
    needs_google = any(
        config[k] in ("firestore", "sheets")
        for k in ("WORKOUT_SOURCE", "WEIGHT_SOURCE")
    )
    needs_firestore = "firestore" in (config["WORKOUT_SOURCE"], config["WEIGHT_SOURCE"])
    needs_sheets = "sheets" in (config["WORKOUT_SOURCE"], config["WEIGHT_SOURCE"])

    if needs_oura:
        print()
        print("  Oura Ring")
        print("  Get a token at: https://cloud.ouraring.com/personal-access-tokens")
        token = _prompt("Personal access token", default=config.get("OURA_TOKEN"), secret=True)
        if token:
            config["OURA_TOKEN"] = token
            print("  Validating...", end=" ")
            ok, detail = _validate_oura_token(token)
            if ok:
                print(f"OK — {detail}")
            else:
                print(f"FAILED — {detail}")
                if not _prompt_yn("Continue anyway?", default=False):
                    print("  Setup cancelled.")
                    return

    if needs_apple:
        print()
        print("  Apple Health")
        print("  Export from: iPhone > Health app > Profile > Export All Health Data")
        path = _prompt("Path to export.xml", default=config.get("APPLE_HEALTH_EXPORT"))
        if path:
            config["APPLE_HEALTH_EXPORT"] = path
            ok, detail = _check_apple_health(path)
            if ok:
                print(f"  OK — {detail}")
            else:
                print(f"  Warning: {detail}")

    if needs_google:
        print()
        print("  Google Cloud Service Account")
        print("  Create at: https://console.cloud.google.com/iam-admin/serviceaccounts")
        sa_path = _prompt(
            "Service account JSON path",
            default=config.get("GOOGLE_SERVICE_ACCOUNT_FILE", "credentials/service_account.json"),
        )
        config["GOOGLE_SERVICE_ACCOUNT_FILE"] = sa_path
        print("  Validating...", end=" ")
        ok, detail = _validate_service_account(sa_path)
        if ok:
            print(f"OK — {detail}")
        else:
            print(f"FAILED — {detail}")
            if not _prompt_yn("Continue anyway?", default=False):
                print("  Setup cancelled.")
                return

        if needs_firestore:
            print()
            project_id = _prompt(
                "Firestore project ID",
                default=config.get("FIRESTORE_PROJECT_ID", "your-firebase-project"),
            )
            config["FIRESTORE_PROJECT_ID"] = project_id
            print("  Validating...", end=" ")
            ok, detail = _validate_firestore(sa_path, project_id)
            if ok:
                print(f"OK — {detail}")
            else:
                print(f"FAILED — {detail}")
                if not _prompt_yn("Continue anyway?", default=False):
                    print("  Setup cancelled.")
                    return

        if needs_sheets:
            print()
            sheet_name = _prompt(
                "Exercise sheet name",
                default=config.get("EXERCISE_SHEET_NAME", "Health OS - Exercise Log"),
            )
            config["EXERCISE_SHEET_NAME"] = sheet_name
            print("  Validating...", end=" ")
            ok, detail = _validate_sheets(sa_path, sheet_name)
            if ok:
                print(f"OK — {detail}")
            else:
                print(f"FAILED — {detail}")
                if not _prompt_yn("Continue anyway?", default=False):
                    print("  Setup cancelled.")
                    return

            reports_sheet = _prompt(
                "Reports log sheet name",
                default=config.get("REPORTS_LOG_SHEET_NAME", "Health OS - Reports Log"),
            )
            config["REPORTS_LOG_SHEET_NAME"] = reports_sheet

    print()

    # Phase 3: Notifications
    print("Notifications")
    print("-" * 40)

    if _prompt_yn("Set up Telegram?", default=bool(config.get("TELEGRAM_BOT_TOKEN"))):
        print("  Create a bot via @BotFather on Telegram")
        print("  Get your chat ID by messaging @userinfobot")
        bot_token = _prompt("Bot token", default=config.get("TELEGRAM_BOT_TOKEN"), secret=True)
        chat_id = _prompt("Chat ID", default=config.get("TELEGRAM_CHAT_ID"))
        if bot_token:
            config["TELEGRAM_BOT_TOKEN"] = bot_token
            config["TELEGRAM_CHAT_ID"] = chat_id
            print("  Validating...", end=" ")
            ok, detail = _validate_telegram(bot_token, chat_id)
            if ok:
                print(f"OK — Bot: {detail}")
            else:
                print(f"FAILED — {detail}")
                if not _prompt_yn("Continue anyway?", default=False):
                    print("  Setup cancelled.")
                    return
    print()

    if _prompt_yn("Set up Gmail?", default=bool(config.get("GMAIL_ADDRESS"))):
        print("  Use a Gmail App Password (not your regular password)")
        print("  Create at: https://myaccount.google.com/apppasswords")
        address = _prompt("Gmail address", default=config.get("GMAIL_ADDRESS"))
        password = _prompt("App password", default=config.get("GMAIL_APP_PASSWORD"), secret=True)
        if address and password:
            config["GMAIL_ADDRESS"] = address
            config["GMAIL_APP_PASSWORD"] = password
            print("  Validating...", end=" ")
            ok, detail = _validate_gmail(address, password)
            if ok:
                print(f"OK — {detail}")
            else:
                print(f"FAILED — {detail}")
                if not _prompt_yn("Continue anyway?", default=False):
                    print("  Setup cancelled.")
                    return
    print()

    # Phase 4: Optional extras
    print("Optional")
    print("-" * 40)

    health_folder = _prompt(
        "Health folder path (blank to skip)",
        default=config.get("HEALTH_FOLDER"),
    )
    if health_folder:
        config["HEALTH_FOLDER"] = health_folder
