def _validate_oura_token(token):
    """Validate Oura token by hitting the personal info endpoint."""
    try:
        resp = requests.get(
            "https://api.ouraring.com/v2/usercollection/personal_info",
            headers={"Authorization": f"Bearer {token}"},
            timeout=10,
        )
        if resp.status_code == 200:
            email = resp.json().get("email", "unknown")
            return True, f"Connected ({email})"
        return False, f"HTTP {resp.status_code}"
    except requests.RequestException as e:
        return False, str(e)


def _validate_telegram(bot_token, chat_id):
    """Validate Telegram bot token via getMe."""
    try:
        resp = requests.get(
            f"https://api.telegram.org/bot{bot_token}/getMe",
            timeout=10,
        )
        if resp.status_code == 200:
            username = resp.json().get("result", {}).get("username", "unknown")
            return True, f"@{username}"
        return False, f"HTTP {resp.status_code}"
    except requests.RequestException as e:
        return False, str(e)


def _validate_gmail(address, password):
    """Validate Gmail by attempting SMTP login (no email sent)."""
    try:
        with smtplib.SMTP_SSL("smtp.gmail.com", 465, timeout=10) as smtp:
            smtp.login(address, password)
        return True, address
    except smtplib.SMTPAuthenticationError:
        return False, "Authentication failed — check app password"
    except Exception as e:
        return False, str(e)


def _validate_service_account(path):
    """Check service account JSON exists and has expected keys."""
    sa_path = Path(path) if Path(path).is_absolute() else BASE_DIR / path
    if not sa_path.exists():
        return False, f"File not found: {sa_path}"
    try:
        data = json.loads(sa_path.read_text())
        if "client_email" in data and "private_key" in data:
            return True, data["client_email"]
        return False, "Missing client_email or private_key"
    except json.JSONDecodeError:
        return False, "Invalid JSON"


def _validate_sheets(sa_path, sheet_name):
    """Try to open the Google Sheet."""
    try:
        import gspread
        resolved = Path(sa_path) if Path(sa_path).is_absolute() else BASE_DIR / sa_path
        gc = gspread.service_account(filename=str(resolved))
        gc.open(sheet_name)
        return True, f"Opened '{sheet_name}'"
    except Exception as e:
        return False, str(e)


def _validate_firestore(sa_path, project_id):
    """Try to connect to Firestore."""
    try:
        from google.cloud import firestore
        resolved = Path(sa_path) if Path(sa_path).is_absolute() else BASE_DIR / sa_path
        client = firestore.Client.from_service_account_json(str(resolved), project=project_id)
        # Attempt a lightweight read to confirm connection
        list(client.collection("workouts").limit(1).stream())
        return True, f"Connected to {project_id}"
    except Exception as e:
        return False, str(e)


def _check_apple_health(path):
    """Check Apple Health export file exists."""
    if not path:
        return False, "Not configured"
    p = Path(path)
    if not p.exists():
        return False, f"File not found: {path}"
    return True, f"Found ({p.stat().st_size / 1024 / 1024:.0f} MB)"


