def run_status():
    """Show configuration and data source status."""
    # Load config directly via os.getenv after dotenv (don't import config module
    # side effects — we want to report what's set vs missing)
    from dotenv import load_dotenv
    load_dotenv(ENV_PATH)

    print()
    print("Health OS Status")
    print("=" * 40)

    # --- Config overview ---
    print()
    print("Config")
    print("-" * 40)

    if ENV_PATH.exists():
        env_vars = _read_existing_env()
        print(f"  .env               Found ({len(env_vars)} vars)")
    else:
        print("  .env               MISSING — run --setup")

    sa_path = os.getenv("GOOGLE_SERVICE_ACCOUNT_FILE", "credentials/service_account.json")
    sa_resolved = Path(sa_path) if Path(sa_path).is_absolute() else BASE_DIR / sa_path
    if sa_resolved.exists():
        print(f"  Service account    Found")
    else:
        print(f"  Service account    MISSING ({sa_resolved})")

    reports_dir = BASE_DIR / "reports"
    if reports_dir.exists():
        count = len(list(reports_dir.glob("*.md")))
        print(f"  Reports dir        {count} reports")
    else:
        print("  Reports dir        Empty")

    # --- Data sources ---
    print()
    print("Data Sources")
    print("-" * 40)

    sleep_source = os.getenv("SLEEP_SOURCE", "oura")
    workout_source = os.getenv("WORKOUT_SOURCE", "firestore")
    weight_source = os.getenv("WEIGHT_SOURCE", "firestore")

    # Sleep
    _print_source_status("Sleep", sleep_source, _check_sleep_source, sleep_source)

    # Workouts
    _print_source_status("Workouts", workout_source, _check_workout_source, workout_source)

    # Weight
    _print_source_status("Weight", weight_source, _check_weight_source, weight_source)

    # Blood tests
    blood_json = BASE_DIR / "data" / "blood_tests.json"
    if blood_json.exists():
        try:
            data = json.loads(blood_json.read_text())
            count = len(data) if isinstance(data, list) else len(data.get("tests", []))
            print(f"  Blood tests        OK    {count} records")
        except Exception:
            print(f"  Blood tests        OK    File exists")
    else:
        print(f"  Blood tests        --    No history yet")

    # Health folder
    health_folder = os.getenv("HEALTH_FOLDER", "")
    if health_folder:
        p = Path(health_folder)
        if p.exists():
            file_count = sum(1 for _ in p.rglob("*") if _.is_file())
            print(f"  Health folder      OK    {file_count} files")
        else:
            print(f"  Health folder      ERR   Path not found")
    else:
        print(f"  Health folder      --    Not configured")

    # --- Notifications ---
    print()
    print("Notifications")
    print("-" * 40)

    # Telegram
    tg_token = os.getenv("TELEGRAM_BOT_TOKEN")
    tg_chat = os.getenv("TELEGRAM_CHAT_ID")
    if tg_token and tg_chat:
        ok, detail = _validate_telegram(tg_token, tg_chat)
        status = f"OK    {detail}" if ok else f"ERR   {detail}"
        print(f"  Telegram           {status}")
    else:
        print(f"  Telegram           --    Not configured")

    # Gmail
    gmail_addr = os.getenv("GMAIL_ADDRESS")
    gmail_pass = os.getenv("GMAIL_APP_PASSWORD")
    if gmail_addr and gmail_pass:
        ok, detail = _validate_gmail(gmail_addr, gmail_pass)
        status = f"OK    {detail}" if ok else f"ERR   {detail}"
        print(f"  Gmail              {status}")
    else:
        print(f"  Gmail              --    Not configured")

    # Webhook
    webhook = os.getenv("WEBHOOK_URL")
    if webhook:
        print(f"  Webhook            OK    Configured")
    else:
        print(f"  Webhook            --    Not configured")

    print()


def _print_source_status(label, source_name, check_fn, source_type):
    """Print a formatted source status line."""
    padded_label = f"{label} ({source_name})"
    try:
        ok, detail = check_fn(source_type)
        status = f"OK    {detail}" if ok else f"ERR   {detail}"
    except Exception as e:
        status = f"ERR   {e}"
    print(f"  {padded_label:<20} {status}")


def _check_sleep_source(source):
    """Check sleep source connectivity and last data date."""
    if source == "oura":
        token = os.getenv("OURA_TOKEN")
        if not token:
            return False, "OURA_TOKEN not set"
        resp = requests.get(
            "https://api.ouraring.com/v2/usercollection/sleep",
            headers={"Authorization": f"Bearer {token}"},
            params={
                "start_date": str(date.today() - timedelta(days=7)),
                "end_date": str(date.today()),
            },
            timeout=10,
        )
        if resp.status_code != 200:
            return False, f"HTTP {resp.status_code}"
        data = resp.json().get("data", [])
        if data:
            last = data[-1].get("day", "?")
            return True, f"Last: {last}"
        return True, "Connected (no recent data)"

    elif source == "apple_health":
        path = os.getenv("APPLE_HEALTH_EXPORT")
        return _check_apple_health(path)

    elif source == "manual":
        manual_dir = BASE_DIR / os.getenv("MANUAL_DATA_DIR", "data/manual")
        sleep_file = manual_dir / "sleep.json"
        if not sleep_file.exists():
            sleep_file = manual_dir / "sleep.csv"
        if sleep_file.exists():
            return True, f"Found {sleep_file.name}"
        return False, "No sleep.json or sleep.csv"

    return False, f"Unknown source: {source}"


