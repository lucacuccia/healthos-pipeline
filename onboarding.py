def _prompt(question, default=None, secret=False):
    """Prompt the user for input. Uses getpass for secrets."""
    suffix = f" [{default}]" if default else ""
    prompt_str = f"  {question}{suffix}: "

    try:
        if secret:
            value = getpass.getpass(prompt_str)
        else:
            value = input(prompt_str)
    except (EOFError, KeyboardInterrupt):
        print()
        raise KeyboardInterrupt

    return value.strip() or default or ""


def _prompt_choice(question, options, default=None):
    """Prompt the user to pick from a list of options."""
    options_str = " / ".join(options)
    default_str = f" [{default}]" if default else ""
    prompt_str = f"  {question} ({options_str}){default_str}: "

    while True:
        try:
            value = input(prompt_str).strip().lower()
        except (EOFError, KeyboardInterrupt):
            print()
            raise KeyboardInterrupt

        if not value and default:
            return default
        if value in options:
            return value
        print(f"    Please enter one of: {options_str}")


def _prompt_yn(question, default=True):
    """Yes/no prompt. Returns bool."""
    hint = "Y/n" if default else "y/N"
    prompt_str = f"  {question} [{hint}]: "

    try:
        value = input(prompt_str).strip().lower()
    except (EOFError, KeyboardInterrupt):
        print()
        raise KeyboardInterrupt

    if not value:
        return default
    return value in ("y", "yes")


def _mask(value):
    """Mask a secret for display: show first 4 chars + dots."""
    if not value or len(value) <= 4:
        return "****"
    return value[:4] + "..." + "*" * 4


