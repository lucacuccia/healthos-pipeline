def _read_existing_env():
    """Parse current .env file into a dict (ignoring comments)."""
    config = {}
    if not ENV_PATH.exists():
        return config

    for line in ENV_PATH.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if "=" in line:
            key, _, value = line.partition("=")
            config[key.strip()] = value.strip()
    return config


def _write_env(config):
    """Write config dict to .env atomically (via temp file + rename)."""
    sections = [
        ("Data Sources", [
            ("SLEEP_SOURCE", "Sleep data provider"),
            ("WORKOUT_SOURCE", "Workout data provider"),
            ("WEIGHT_SOURCE", "Weight data provider"),
        ]),
        ("Oura Ring", [
            ("OURA_TOKEN", "Personal access token"),
        ]),
        ("Google Cloud", [
            ("GOOGLE_SERVICE_ACCOUNT_FILE", "Service account JSON path"),
            ("FIRESTORE_PROJECT_ID", "Firestore project ID"),
            ("EXERCISE_SHEET_NAME", "Exercise log sheet name"),
            ("REPORTS_LOG_SHEET_NAME", "Reports log sheet name"),
        ]),
        ("Apple Health", [
            ("APPLE_HEALTH_EXPORT", "Path to export.xml"),
        ]),
        ("Manual Data", [
            ("MANUAL_DATA_DIR", "Manual data directory"),
        ]),
        ("Telegram", [
            ("TELEGRAM_BOT_TOKEN", "Bot token"),
            ("TELEGRAM_CHAT_ID", "Chat ID"),
        ]),
        ("Gmail", [
            ("GMAIL_ADDRESS", "Gmail address"),
            ("GMAIL_APP_PASSWORD", "App password"),
        ]),
        ("Health Folder", [
            ("HEALTH_FOLDER", "Google Drive health folder path"),
        ]),
        ("Cloudflare Worker", [
            ("WEBHOOK_URL", "Webhook URL"),
            ("RESPONSES_SECRET", "Responses secret"),
        ]),
    ]

    lines = ["# Health OS Configuration", f"# Generated by --setup on {date.today()}", ""]

    for section_name, variables in sections:
        # Only write section if at least one var has a value
        section_lines = []
        for key, comment in variables:
            value = config.get(key, "")
            if value:
                section_lines.append(f"# {comment}")
                section_lines.append(f"{key}={value}")

        if section_lines:
            lines.append(f"# --- {section_name} ---")
            lines.extend(section_lines)
            lines.append("")

    content = "\n".join(lines) + "\n"

    # Atomic write: tmp file + rename
    tmp_path = ENV_PATH.with_suffix(".tmp")
    tmp_path.write_text(content)
    tmp_path.rename(ENV_PATH)


